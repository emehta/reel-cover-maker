/**
 * Draws "Goo", the hand Stickery's drawn lettering is squeezed along, and
 * writes it as stroke data. `node scripts/goo-font.mjs`, then commit what it
 * writes.
 *
 * Goo is drawn after Main Sticker 2's "aren't" and "what": a round,
 * running hand, its curves full, drawn to be laid in paste thin through the
 * stroke and heavy at its ends, the letters run into each other. A w is
 * two round bowls with a low,
 * round peak between them, an a a lying lens under a roof, an e a loop on
 * a rising bar; a stem that ends
 * on the baseline runs on to the right, so the next letter can run into
 * it; a t is tall and curved, its crossbar high and rising, for the swash
 * a word's last t swings out. Only the lowercase (and a shorter
 * apostrophe, a bead) is Goo's own: capitals, figures and other marks are Drip's
 * (scripts/drip-font.mjs), which share its heights.
 *
 * Authored as Drip is: points the stroke passes through, smoothed by a
 * centripetal Catmull and Rom spline, `*` a corner and a closing `z` a loop,
 * y up from the baseline in units of 1000 to the em (x-height 480,
 * ascenders 760, descenders 260), written y down.
 *
 * Goo is this project's own drawing, under the project's licence.
 */

