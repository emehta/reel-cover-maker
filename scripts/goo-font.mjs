/** Every lowercase letter drawn this much wider than authored, as Main Sticker 2's are for their height. */
const WIDE = 1.1;

const widened = (stroke) =>
  stroke.replace(/(\*?)(-?\d+),(-?\d+)/g, (_, corner, x, y) => `${corner}${Math.round(Number(x) * WIDE)},${y}`);

