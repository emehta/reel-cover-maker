/** Accents, drawn over (or under) a letter whose ink runs from `x0` to `x1` and up to `top`. */
const ACCENTS = {
  "\u0300": (cx, top) => [`*${cx - 55},${top + 150} *${cx + 35},${top + 25}`],
  "\u0301": (cx, top) => [`*${cx + 55},${top + 150} *${cx - 35},${top + 25}`],
  "\u0302": (cx, top) => [`*${cx - 85},${top + 25} *${cx},${top + 140} *${cx + 85},${top + 25}`],
  "\u0303": (cx, top) => [`${cx - 95},${top + 45} ${cx - 45},${top + 110} ${cx + 40},${top + 55} ${cx + 95},${top + 120}`],
  "\u0308": (cx, top) => [`${cx - 75},${top + 75}`, `${cx + 75},${top + 75}`],
  "\u030a": (cx, top) => [`${cx},${top + 160} ${cx - 55},${top + 105} ${cx},${top + 45} ${cx + 55},${top + 105} ${cx},${top + 160} z`],
  "\u0327": (cx) => [`${cx},0 ${cx + 45},-70 ${cx - 25},-140`],
};

function parse(stroke) {
  const closed = /\sz$/.test(stroke);
  const body = closed ? stroke.replace(/\s*z$/, "") : stroke;
  const points = body
    .trim()
    .split(/\s+/)
    .map((token) => {
      const corner = token.startsWith("*");
      const [x, y] = token.replace("*", "").split(",").map(Number);
      if (!Number.isFinite(x) || !Number.isFinite(y)) throw new Error(`Bad point ${token} in ${stroke}`);
      return { x, y, corner };
    });
  return { points, closed };
}

/** A centripetal Catmull and Rom spline through `p`, `steps` points a span, both ends kept. */
function spline(p, closed, steps = 6) {
  if (p.length < 3 && !closed) return p;
  const at = (i) => (closed ? p[(i + p.length) % p.length] : p[Math.max(0, Math.min(p.length - 1, i))]);
  const out = [];
  const spans = closed ? p.length : p.length - 1;
  for (let i = 0; i < spans; i += 1) {
    const p0 = at(i - 1);
    const p1 = at(i);
    const p2 = at(i + 1);
    const p3 = at(i + 2);
    const dist = (a, b) => Math.max(1e-6, Math.hypot(b.x - a.x, b.y - a.y) ** 0.5);
    const t0 = 0;
    const t1 = t0 + dist(p0, p1);
    const t2 = t1 + dist(p1, p2);
    const t3 = t2 + dist(p2, p3);
    for (let s = 0; s < steps; s += 1) {
      const t = t1 + ((t2 - t1) * s) / steps;
      const lerp = (a, b, ta, tb) => ({
        x: ((tb - t) / (tb - ta)) * a.x + ((t - ta) / (tb - ta)) * b.x,
        y: ((tb - t) / (tb - ta)) * a.y + ((t - ta) / (tb - ta)) * b.y,
      });
      const a1 = lerp(p0, p1, t0, t1);
      const a2 = lerp(p1, p2, t1, t2);
      const a3 = lerp(p2, p3, t2, t3);
      const b1 = lerp(a1, a2, t0, t2);
      const b2 = lerp(a2, a3, t1, t3);
      out.push(lerp(b1, b2, t1, t2));
    }
  }
  out.push(closed ? p[0] : p[p.length - 1]);
  return out;
}

/** A stroke as a flat list, smoothed between its corners, y down. */
function flatten(stroke) {
  const { points, closed } = parse(stroke);
  if (points.length === 1) return [Math.round(points[0].x), -Math.round(points[0].y)];
  const runs = [];
  let run = [points[0]];
  for (let i = 1; i < points.length; i += 1) {
    run.push(points[i]);
    if (points[i].corner && i < points.length - 1) {
      runs.push(run);
      run = [points[i]];
    }
  }
  runs.push(run);
  const smooth = closed && runs.length === 1 ? spline(points.slice(0, -1), true) : runs.flatMap((r, i) => spline(r, false).slice(i ? 1 : 0));
  const flat = [];
  for (const q of smooth) {
    const x = Math.round(q.x);
    const y = -Math.round(q.y);
    if (flat.length && flat[flat.length - 2] === x && flat[flat.length - 1] === y) continue;
    flat.push(x, y);
  }
  return flat;
}

const glyphs = {};
for (const [character, [advance, strokes]] of Object.entries(GLYPHS)) {
  glyphs[character] = [advance, strokes.map(flatten)];
}

// Every accented Latin-1 letter: its base letter, an i or j without its dot, and the accent.
for (let code = 0xc0; code <= 0xff; code += 1) {
  const character = String.fromCharCode(code);
  if (glyphs[character]) continue;
  const parts = character.normalize("NFD");
  const base = parts[0];
  const marks = [...parts.slice(1)];
  if (!marks.length || !GLYPHS[base] || !marks.every((m) => ACCENTS[m])) continue;
  const [advance, strokes] = GLYPHS[base];
  const dotless = base === "i" || base === "j" ? strokes.filter((s) => s.trim().split(/\s+/).length > 1) : strokes;
  const tall = base !== base.toLowerCase();
  const top = tall ? CAP + 40 : X + 70;
  const cx = advance / 2 - (base === "i" ? 0 : 5);
  glyphs[character] = [advance, [...dotless, ...marks.flatMap((m) => ACCENTS[m](cx, top))].map(flatten)];
}
// Two that NFD does not build: a slashed o, and the y with two dots is built above.
glyphs["\u00f8"] = [GLYPHS.o[0], [...GLYPHS.o[1], "*40,-20 *330,500"].map(flatten)];
glyphs["\u00d8"] = [GLYPHS.O[0], [...GLYPHS.O[1], "*40,-30 *400,730"].map(flatten)];

const data = { id: "drip", name: "Drip", upm: 1000, glyphs };
