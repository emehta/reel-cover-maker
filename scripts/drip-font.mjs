/**
 * Draws "Drip", the hand Pasty letters its paste in, and writes it as
 * stroke data. `node scripts/drip-font.mjs`, then commit what it writes.
 *
 * The single-line fonts from the plotter world are drawn for a pen: Elfin
 * has serifs and straight stems, and paste squeezed along them reads as a
 * storybook, stiff and straight. Drip is drawn for a nozzle instead, after
 * the drippy sign painter's hands Pasty is modelled on: tall, narrow letters
 * with no serifs, curves where a pen would rule a line, a hooked l, a single
 * storey a and g. Capitals and lowercase share a stem height closely enough
 * that a word may mix them, as those hands do.
 *
 * Each stroke is a few points the paste passes through, smoothed by a
 * centripetal Catmull and Rom spline; a point marked with `*` is a corner,
 * where the spline stops and starts again, and a stroke ending in `z` is a
 * closed loop. Authored with y up from the baseline in units of 1000 to the
 * em (capitals 700 tall, x-height 480), written y down, as the other stroke
 * fonts are. Accented letters are built from their base letter and the
 * accent's own strokes, so every Latin-1 letter is drawn.
 *
 * Drip is this project's own drawing, under the project's licence.
 */

